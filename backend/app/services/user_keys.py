"""Users' own provider API keys ("bring your own key").

Keys are encrypted with Fernet (AEO_SECRETS_KEY) before they are stored, are never returned by the API
(only the last 4 characters), and are never logged. `user_settings()` gives a copy of the server settings
with the user's keys filled in, so providers work unchanged and per-user keys never leak across users.
"""

from __future__ import annotations

import base64
import hashlib
import logging
from dataclasses import dataclass

import httpx
from cryptography.fernet import Fernet, InvalidToken
from pydantic import SecretStr
from sqlalchemy import select
from sqlalchemy.orm import Session

from app.config import Settings, get_settings
from app.models import USER_KEY_PROVIDERS, UserApiKey

logger = logging.getLogger(__name__)


@dataclass(frozen=True)
class KeySpec:
    label: str
    field: str  # Settings attribute
    url: str  # where to create a key
    purpose: str


KEY_SPECS: dict[str, KeySpec] = {
    "openai": KeySpec("OpenAI (ChatGPT)", "openai_api_key", "https://platform.openai.com/api-keys",
                      "Test visibility in ChatGPT (OpenAI API with web search)."),
    "anthropic": KeySpec("Anthropic (Claude)", "anthropic_api_key", "https://console.anthropic.com/settings/keys",
                         "Test visibility in Claude (Anthropic API with web search). Also writes questions and drafts if no NVIDIA key."),
    "gemini": KeySpec("Google Gemini", "gemini_api_key", "https://aistudio.google.com/apikey",
                      "Test visibility in Gemini (Gemini API with Google Search). Google AI Studio has a free tier."),
    "perplexity": KeySpec("Perplexity", "perplexity_api_key", "https://www.perplexity.ai/settings/api",
                          "Test visibility in Perplexity. Can also power backlink discovery."),
    "nvidia": KeySpec("NVIDIA (analysis model)", "nvidia_api_key", "https://build.nvidia.com",
                      "Writes questions and lists which businesses each answer recommends. Not tested as an assistant."),
    "brave": KeySpec("Brave Search", "brave_api_key", "https://api-dashboard.search.brave.com",
                     "Finds existing mentions and backlink opportunities."),
}
assert set(KEY_SPECS) == set(USER_KEY_PROVIDERS)

MIN_KEY_LEN, MAX_KEY_LEN = 16, 400


class UserKeyError(Exception):
    def __init__(self, status: int, code: str, message: str) -> None:
        super().__init__(message)
        self.status, self.code, self.message = status, code, message


def _fernet(settings: Settings) -> Fernet:
    if not settings.user_keys_enabled:
        raise UserKeyError(503, "user_keys_disabled",
                        "Saving API keys is turned off on this server (the admin must set AEO_SECRETS_KEY).")
    raw = settings.secrets_key.get_secret_value().strip().encode()
    try:
        return Fernet(raw)
    except (ValueError, TypeError):
        pass
    # Any other long random secret (e.g. one generated by the hosting platform): derive a Fernet key from it
    if len(raw) < 32:
        raise UserKeyError(503, "user_keys_misconfigured", "The server's AEO_SECRETS_KEY is too short (use 32+ random characters).")
    return Fernet(base64.urlsafe_b64encode(hashlib.sha256(raw).digest()))


def clean_key(value: str) -> str:
    key = (value or "").strip()
    if not (MIN_KEY_LEN <= len(key) <= MAX_KEY_LEN) or not key.isascii() or any(c.isspace() or not c.isprintable() for c in key):
        raise UserKeyError(400, "invalid_key_format", "That doesn't look like an API key. Paste the whole key, with no spaces.")
    return key


def _decrypt(fernet: Fernet, row: UserApiKey) -> str | None:
    try:
        return fernet.decrypt(row.ciphertext.encode()).decode()
    except InvalidToken:
        return None  # server secret changed: the user must re-enter the key


def _rows(db: Session, user_id: int | None) -> list[UserApiKey]:
    if user_id is None:
        return []
    return list(db.scalars(select(UserApiKey).where(UserApiKey.user_id == user_id)))


def user_settings(db: Session, user_id: int | None, base: Settings | None = None) -> Settings:
    """Server settings with this user's keys applied (and the server's own keys removed if not allowed)."""
    s = base or get_settings()
    update: dict = {}
    if not s.use_server_api_keys:
        update = {spec.field: None for spec in KEY_SPECS.values()}
    rows = _rows(db, user_id) if s.user_keys_enabled else []
    if rows:
        fernet = _fernet(s)
        for row in rows:
            key = _decrypt(fernet, row)
            if key and row.provider in KEY_SPECS:
                update[KEY_SPECS[row.provider].field] = SecretStr(key)
    return s.model_copy(update=update) if update else s


def own_key_providers(db: Session, user_id: int | None) -> set[str]:
    s = get_settings()
    if not s.user_keys_enabled:
        return set()
    fernet = _fernet(s)
    return {r.provider for r in _rows(db, user_id) if _decrypt(fernet, r)}


def uses_own_key(db: Session, user_id: int | None, provider: str | None) -> bool:
    return provider is not None and provider in own_key_providers(db, user_id)


def key_status(db: Session, user_id: int) -> dict:
    s = get_settings()
    rows = {r.provider: r for r in _rows(db, user_id)}
    fernet = _fernet(s) if s.user_keys_enabled and rows else None
    keys = []
    for provider, spec in KEY_SPECS.items():
        row = rows.get(provider)
        readable = bool(row and fernet and _decrypt(fernet, row))
        keys.append({
            "provider": provider, "label": spec.label, "purpose": spec.purpose, "get_key_url": spec.url,
            "saved": readable, "needs_reentry": bool(row) and not readable,
            "last4": row.last4 if readable else None, "verified": row.verified if readable else None,
            "updated_at": row.updated_at.isoformat() if row and readable else None,
            "server_key_available": s.use_server_api_keys and Settings.has_key(getattr(s, spec.field)),
        })
    return {"enabled": s.user_keys_enabled, "server_keys_used": s.use_server_api_keys, "keys": keys}


# --- Key checks: a free, read-only request to each provider's model list. Fixed URLs only.
_CHECKS = {
    "openai": ("https://api.openai.com/v1/models", lambda k: {"Authorization": f"Bearer {k}"}),
    "anthropic": ("https://api.anthropic.com/v1/models", lambda k: {"x-api-key": k, "anthropic-version": "2023-06-01"}),
    "gemini": ("https://generativelanguage.googleapis.com/v1beta/models", lambda k: {"x-goog-api-key": k}),
}


def check_key(provider: str, key: str, transport: httpx.BaseTransport | None = None) -> bool | None:
    """True = accepted, False = rejected by the provider, None = couldn't be checked (checked on first use)."""
    if provider not in _CHECKS:
        return None
    url, headers = _CHECKS[provider]
    try:
        with httpx.Client(timeout=15, transport=transport, trust_env=False) as client:
            resp = client.get(url, headers=headers(key))
    except httpx.HTTPError as exc:
        logger.info("could not check %s key: %s", provider, type(exc).__name__)
        return None
    if resp.status_code == 200:
        return True
    if resp.status_code in (400, 401, 403):
        return False
    return None


key_checker = check_key  # tests replace this


def save_key(db: Session, user_id: int, provider: str, raw: str) -> UserApiKey:
    if provider not in KEY_SPECS:
        raise UserKeyError(404, "unknown_provider", "Unknown provider")
    fernet = _fernet(get_settings())
    key = clean_key(raw)
    verified = key_checker(provider, key)
    if verified is False:
        raise UserKeyError(400, "key_rejected", f"{KEY_SPECS[provider].label} rejected this key. Check that you copied all of it and that it's active.")
    row = db.scalar(select(UserApiKey).where(UserApiKey.user_id == user_id, UserApiKey.provider == provider))
    if row is None:
        row = UserApiKey(user_id=user_id, provider=provider)
        db.add(row)
    row.ciphertext = fernet.encrypt(key.encode()).decode()
    row.last4 = key[-4:]
    row.verified = verified
    db.commit()
    return row


def delete_key(db: Session, user_id: int, provider: str) -> None:
    row = db.scalar(select(UserApiKey).where(UserApiKey.user_id == user_id, UserApiKey.provider == provider))
    if row is not None:
        db.delete(row)
        db.commit()
